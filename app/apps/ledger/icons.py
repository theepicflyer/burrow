"""Category icons: a curated set of Phosphor Icons (Bold), drawn from one SVG sprite.

The library is generated by ``frontend/icons/generate.cjs`` into ``icons.json`` (groups,
labels and search words for the picker, plus words in a category name that suggest an icon)
and ``static/img/category-icons.svg``.
"""

import json
import re
from functools import cache
from pathlib import Path

# Stored in Category.icon to show the first letter instead of a guessed icon.
LETTER = "letter"
GENERIC = "dots-three"


@cache
def library() -> dict:
    return json.loads((Path(__file__).with_name("icons.json")).read_text())


@cache
def names() -> frozenset:
    return frozenset(i["n"] for g in library()["groups"] for i in g["icons"])


def guess(name: str) -> str:
    """An icon for a category called ``name``, from the words in it; "" if none fits."""
    match = library()["match"]
    found = []
    for word in re.findall(r"[a-z]+", name.lower()):
        for w in (word, word[:-1] if word.endswith("s") else None):
            if w and w in match:
                found.append(match[w])
                break
    # "Other income" should get the income icon, not the catch-all one.
    specific = [i for i in found if i != GENERIC]
    return (specific or found or [""])[0]
