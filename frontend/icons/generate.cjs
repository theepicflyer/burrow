#!/usr/bin/env node
/*
 * Builds the category icon library from Phosphor Icons (Bold, MIT) and frontend/icons/library.json.
 *
 *   node frontend/icons/generate.cjs
 *
 * Outputs (generated, do not hand-edit):
 *   app/static/img/category-icons.svg   one <symbol id="i-NAME"> per icon, used as <svg><use href="…#i-NAME"></svg>
 *   app/apps/ledger/icons.json          groups, labels and search words for the picker, and the name → icon map
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const PKG = path.join(__dirname, '..', 'node_modules', '@phosphor-icons', 'core');
const meta = new Map(require(path.join(PKG, 'dist', 'index.umd.js')).icons.map((i) => [i.name, i]));
const lib = JSON.parse(fs.readFileSync(path.join(__dirname, 'library.json'), 'utf8'));

const label = (name) => name.replace(/-/g, ' ').replace(/^./, (c) => c.toUpperCase());
const symbols = [];
const seen = new Set();
const groups = lib.groups.map(([title, list]) => ({
  label: title,
  icons: list.split(/\s+/).filter(Boolean).map((name) => {
    const m = meta.get(name);
    if (!m) throw new Error(`Unknown Phosphor icon: ${name}`);
    if (!seen.has(name)) {
      seen.add(name);
      const svg = fs.readFileSync(path.join(PKG, 'assets', 'bold', `${name}-bold.svg`), 'utf8');
      const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
      symbols.push(`<symbol id="i-${name}" viewBox="0 0 256 256">${inner}</symbol>`);
    }
    const words = new Set([...name.split('-'), ...(m.tags || []).filter((t) => !t.startsWith('*'))]);
    return { n: name, l: label(name), k: [...words].join(' ').toLowerCase() };
  }),
}));

const match = {};
for (const [words, icon] of Object.entries(lib.match)) {
  if (!seen.has(icon)) throw new Error(`match uses ${icon}, which is not in a group`);
  for (const w of words.split(/\s+/)) match[w] = icon;
}

const license = fs.readFileSync(path.join(PKG, 'LICENSE'), 'utf8').trim().replace(/--/g, '- -');
fs.writeFileSync(
  path.join(ROOT, 'app/static/img/category-icons.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" fill="currentColor">\n<!-- GENERATED by frontend/icons/generate.cjs. Icons: Phosphor Icons (https://phosphoricons.com), Bold weight.\n${license}\n-->\n${symbols.join('\n')}\n</svg>\n`,
);
fs.writeFileSync(path.join(ROOT, 'app/apps/ledger/icons.json'), JSON.stringify({ groups, match }) + '\n');
console.log(`${seen.size} icons, ${Object.keys(match).length} name words`);
