#!/usr/bin/env node
/*
 * Regenerates WYGIWYH's copy of the Burrow design system from the vendored sources in this
 * folder (bundle.js, bundle.css, tokens.json — copied from the Burrow design-system artifact).
 *
 *   node frontend/burrow/generate.cjs
 *
 * Outputs (all generated, do not hand-edit):
 *   frontend/src/styles/burrow.generated.css   tokens as CSS variables + the bh-* component classes
 *   app/static/img/burrow/characters/*.svg     the cast, one file per animal and mood
 *   app/static/img/burrow/traces/*.svg         the traces
 *   app/static/img/burrow/loader.svg           Gali's footprints stepping across (self-animating)
 *   app/templates/burrow/scenes/*.html         inline SVG scenery that follows the theme
 *                                              (habitats, stash acorns, wreath ring, world)
 */
const fs = require('fs');
const path = require('path');

const HERE = __dirname;
const ROOT = path.resolve(HERE, '..', '..');
const out = (rel, text) => {
  const p = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, text);
};

/* ---- run the bundle with a tiny string renderer standing in for React ---- */
const ATTR = { className: 'class', strokeWidth: 'stroke-width', strokeLinecap: 'stroke-linecap', strokeLinejoin: 'stroke-linejoin', strokeDasharray: 'stroke-dasharray', strokeDashoffset: 'stroke-dashoffset' };
const UNITLESS = new Set(['opacity', 'zIndex', 'flex', 'fontWeight', 'lineHeight']);
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const styleStr = (o) => Object.entries(o).filter(([, v]) => v != null && v !== '')
  .map(([k, v]) => k.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase()) + ':' + (typeof v === 'number' && !UNITLESS.has(k) ? v + 'px' : v)).join(';');
const h = (type, props, ...children) => ({ type, props: props || {}, children });
function render(n) {
  if (n == null || n === false || n === true) return '';
  if (Array.isArray(n)) return n.map(render).join('');
  if (typeof n === 'string' || typeof n === 'number') return esc(n);
  if (typeof n.type === 'function') {
    const kids = n.children.length === 1 ? n.children[0] : n.children.length ? n.children : n.props.children;
    return render(n.type(Object.assign({}, n.props, { children: kids })));
  }
  let a = '';
  for (const [k, v] of Object.entries(n.props)) {
    if (['children', 'dangerouslySetInnerHTML', 'key', 'ref'].includes(k) || v == null || v === false || typeof v === 'function') continue;
    if (k === 'style') { const s = styleStr(v); if (s) a += ' style="' + esc(s) + '"'; continue; }
    a += ' ' + (ATTR[k] || k) + '="' + esc(v === true ? '' : v) + '"';
  }
  const inner = n.props.dangerouslySetInnerHTML ? n.props.dangerouslySetInnerHTML.__html : render(n.children.length ? n.children : n.props.children);
  return '<' + n.type + a + '>' + inner + '</' + n.type + '>';
}
const React = { createElement: h, Fragment: 'frag', useState: (v) => [typeof v === 'function' ? v() : v, () => {}], useEffect: () => {}, useLayoutEffect: () => {}, useRef: (v) => ({ current: v }), useMemo: (f) => f(), useCallback: (f) => f };
const win = { React };
new Function('window', fs.readFileSync(path.join(HERE, 'bundle.js'), 'utf8'))(win);
const B = win.Burrow;

/* ---- CSS: tokens + component classes ---- */
const tokens = JSON.parse(fs.readFileSync(path.join(HERE, 'tokens.json'), 'utf8'));
const val = (v, theme) => {
  if (v && typeof v === 'object') v = v[theme] ?? v.light;
  const m = /^\{([\w.-]+)\}$/.exec(v);
  return m ? `var(--${m[1]})` : v;
};
// money is Kacang's app, so its home colour (accent) is mint rather than the default tomato.
const ACCENT = { accent: 'var(--mint)', 'accent-soft': 'var(--mint-soft)' };
const themed = (theme) => [...tokens.color.tokens, ...tokens.shadow.tokens]
  .map((t) => `  --${t.name}: ${ACCENT[t.name] || val(t.value, theme)};`).join('\n');
const fixed = ['spacing', 'radius', 'border'].flatMap((f) => tokens[f].tokens.map((t) => `  --${t.name}: ${t.value};`));
const fam = tokens.type.families;
fixed.push(`  --font-display: "Fredoka Variable", ${fam.display.replace(/^Fredoka,\s*/, '')};`);
fixed.push(`  --font-sans: "Figtree Variable", ${fam.sans.replace(/^Figtree,\s*/, '')};`);
const components = fs.readFileSync(path.join(HERE, 'bundle.css'), 'utf8')
  .replace(/^@import url\([^)]*\);\s*/m, '') // fonts are self-hosted via @fontsource
  .replace(/^\/\* Burrow component styles\.[^\n]*\n/m, '')
  .replace(/^\.bh-app, body \{[^\n]*\n/m, '')
  .replace(/^\.bh-app--money \{[^\n]*\n/m, '')
  .trim();
out('frontend/src/styles/burrow.generated.css', `/* GENERATED by frontend/burrow/generate.cjs from the Burrow design system. Do not edit. */

:root {
${fixed.join('\n')}
}

/* Dark is WYGIWYH's default theme. */
:root,
[data-theme=wygiwyh_dark] {
${themed('dark')}
}

[data-theme=wygiwyh_light] {
${themed('light')}
}

@layer components {
${components}
}
`);

/* ---- art as static files ---- */
const CAST = { bao: 'Bao', kacang: 'Kacang', gali: 'Gali', kayu: 'Kayu' };
for (const who of Object.keys(CAST)) {
  for (const mood of B.MOODS) out(`app/static/img/burrow/characters/${who}-${mood}.svg`, B.mascotSVG(who, mood, `${CAST[who]}, ${mood}`));
}
const TRACES = ['seed', 'crumbs', 'sunflower', 'berry', 'acorn', 'leaf', 'pinecone', 'mushroom', 'footprint', 'hole', 'mound', 'pebble', 'twig', 'log', 'chewed', 'chips'];
for (const t of TRACES) out(`app/static/img/burrow/traces/${t}.svg`, B.traceSVG(t, 64));

// Loader: the bundle's footprints trail, made standalone so it can be a CSS background.
const loader = render(h(B.Loader, { kind: 'footprints' }));
const loaderSvg = loader.match(/<svg[\s\S]*<\/svg>/)[0]
  .replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ')
  .replace(/(<svg[^>]*>)/, '$1<style>.bh-loader__print{opacity:.12;animation:s 1.4s steps(1) infinite}@keyframes s{0%{opacity:1}50%{opacity:.12}}@media (prefers-reduced-motion:reduce){.bh-loader__print{animation:none;opacity:.6}}</style>');
out('app/static/img/burrow/loader.svg', loaderSvg);

/* ---- inline scenery for templates (uses hb-* classes, so it follows the theme) ---- */
const HEADER = '{# GENERATED by frontend/burrow/generate.cjs from the Burrow design system. Do not edit. #}\n';
for (const kind of ['meadow', 'oak', 'burrow', 'river']) {
  const html = render(h(B.Habitat, { kind, character: false }, '@@CONTENT@@'));
  const inner = html.slice(html.indexOf('>') + 1, html.indexOf('<div class="bh-habitat__content">'));
  out(`app/templates/burrow/scenes/habitat_${kind}.html`, HEADER + inner + '\n');
}

// Stash: 15 acorn slots; the template shows slot k when acorns >= k (acorns = round(share * 15)).
const stashSvg = (v) => render(h(B.Stash, { name: '', value: v, max: 15, valueText: '' })).match(/<svg[\s\S]*<\/svg>/)[0];
const empty = stashSvg(0), full = stashSvg(15);
const foot = empty.slice(empty.indexOf('<g transform="translate(64 80)">'), empty.lastIndexOf('</svg>'));
const base = empty.slice(0, empty.indexOf('<g transform="translate(64 80)">'));
let slots = '';
for (let k = 1; k <= 15; k++) {
  const prev = stashSvg(k - 1).replace(foot, ''), cur = stashSvg(k);
  const acorn = cur.slice(prev.length - '</svg>'.length, cur.length - '</svg>'.length);
  slots += `{% if acorns >= ${k} %}${acorn}{% endif %}`;
}
if (!full.startsWith(base)) throw new Error('stash: unexpected markup');
out('app/templates/burrow/scenes/stash_art.html', HEADER + base + slots + `{% if acorns <= 0 %}${foot}{% endif %}</svg>\n`);

// Wreath ring (money's month): 26 oak leaves; leaf i is lit when leaves > i (leaves = round(share * 26)).
const ring = render(h(B.Ring, { value: 0, max: 1, variant: 'wreath', size: 196 }, '@@CENTER@@'));
let li = 0;
const wreath = ring
  .replace(/class="bh-wleaf"/g, () => `class="bh-wleaf{% if leaves > ${li++} %} is-on{% endif %}"`)
  .replace('@@CENTER@@', '{{ slot }}');
out('app/templates/burrow/scenes/wreath.html', HEADER + wreath + '\n');

out('app/templates/burrow/scenes/world.html', HEADER + '<div class="bh-world-wrap">' + B.worldSVG() + '</div>\n');

console.log('Burrow assets regenerated.');
